## Struttura obbligatoria di ogni copy
HOOK sul dolore → 2 righe su cosa abbiamo creato → DOMANDA aperta → UNA sola CTA.
1. Leva emozionale: mai "Scopri la funzione X". Si parte dalla frustrazione: "Odi pure tu la cliente delle 18 che disdice alle 17:15?".
2. Domanda per l'algoritmo: chiudere tirando dentro la loro esperienza: "Voi l'ora buca ve la fate pagare o abbozzate?".
3. CTA a zero attrito: una sola azione.

Il messaggio principale è sempre situazione reale + conseguenza, in uno di questi tre schemi:
PROBLEMA → CONSEGUENZA · AZIONE → CONSEGUENZA · ERRORE → COSTO.
La grafica mostra la conseguenza visivamente, mai uno screenshot di feature.
Test finale: togli il nome del prodotto dal testo. Se il messaggio funziona lo stesso, la copy è corretta.

## Tono
La copy deve suonare come un PT che parla al bar dopo una giornata di lavoro: situazioni concrete, parole semplici, contrasti reali (per esempio "5 clienti vs 30"), nessuna formula astratta.
Sì: informale, diretto, da spogliatoio; partire dal dolore non dalla feature; massimo 3–4 emoji; chiudere con una domanda aperta; una sola CTA.
No: gergo aziendale o tono ingessato; "Scopri la nostra funzione…"; muri di testo e troppe richieste; spocchia o promesse gonfiate; più CTA nello stesso post.

