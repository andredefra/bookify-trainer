## Il problema che risolviamo
Essere un personal trainer indipendente oggi vuol dire essere un ottimo tecnico in sala e gestire un'azienda bendato. L'85% dei trainer italiani lavora immerso nel caos. Quattro sintomi:

1. Frammentazione e tempo perso — le cinque ore nascoste. La gestione amministrativa è spalmata su fogli Excel, note sul telefono e appuntamenti su carta. Fino a 5 ore a settimana non retribuite spese a incrociare agende e rispondere a vocali logistici, sottratte alla vendita e all'assistenza reale.
2. La "black box" dell'esecuzione. Il PT manda un PDF con la scheda e spera. Nessuna visibilità su cosa fa davvero il cliente in palestra, nessuna cronologia della progressione dei carichi, solo messaggi frammentati su WhatsApp tipo "oggi ho fatto 60 kg anziché 50".
3. Onboarding alla cieca. Quando arriva un nuovo cliente non c'è storico, non c'è un posto dove carica anamnesi, dati iniziali e limitazioni fisiche. Si riparte da zero affidandosi alla memoria.
4. Check-in e tracking dispersi. Foto di update, misure, resoconti su umore e sonno finiscono nella galleria del telefono personale del trainer. Non essendo organizzati, i risultati diventano impossibili da confrontare graficamente per motivare il cliente.

Risultato: il trainer tocca un tetto di cristallo. Senza progressione chirurgica l'esperienza del cliente resta mediocre, la fidelizzazione cala e i pacchetti non si rinnovano.

## La soluzione
MyPersonal.fit non è un generatore di schede: è il primo sistema operativo aziendale pensato per abbattere il lavoro invisibile del PT e alzare il valore percepito dal suo cliente. Già con le prime due fasce (Basic ed Essential) l'ecosistema è bilaterale e il lato cliente è completo dal giorno zero:
- Client Hub: il cliente apre l'app, vede l'allenamento nel Session Player interattivo, compila il log di serie, ripetizioni e pesi sul momento. Fine dei PDF statici.
- Check-in sistematizzati: peso, misure, scale di bio-feedback 0–10 per umore e sonno, foto. Tutto salvato e incrociato nelle dashboard del trainer.
- Vetrina e CRM: landing page professionale "link in bio" da cui intercettare contatti, che confluiscono nella Sales Dashboard separando lead, attivi e paganti.
- Calendario e automazione: calendario bidirezionale sincronizzato, liste d'attesa per le classi (Essential) e status "In sessione" che blocca le notifiche mentre il coach è con un cliente, lasciando all'assistente AI il follow-up.

## Strategia competitiva — "spezzamercato"
Il target sono trainer i cui introiti non giustificano 300 € l'anno di software non localizzato.

Contro i colossi americani (Trainerize, TrueCoach, CoachPlus): barriere d'ingresso alte, dai 20 ai 30 € al mese che salgono a 60–80 al crescere degli utenti, funzioni disperse e nessun adattamento a contabilità e privacy italiane. Prodotti elitari o in fasce grigie che il trainer fatica a giustificare come costo fisso.

Contro il vero rivale — Excel, Drive e WhatsApp: un mix anarchico ma gratuito. Qui si vince convertendo le mentalità con un valore asimmetrico sul prezzo:
- Basic a 1,99 €/mese: annienta la reticenza del coach old-school. Al costo di una colazione: clienti illimitati, dati storici, pagina link-in-bio e messaggistica professionale.
- Essential a 9 €/mese, il cavallo di Troia: meno di un abbonamento a uno streaming. Qui il trainer sblocca calendario full sync, liste d'attesa, programmi personalizzati erogati sul telefono del cliente e i form di check-in che rimandano i dati nella dashboard.

