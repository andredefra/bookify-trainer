// Function to get equipment image
export const getEquipmentImage = (equipment: string): string => {
  const normalizedEquipment = equipment.toLowerCase();
  return equipmentImageMap[normalizedEquipment] || equipmentImageMap['various'];
};

// Function to generate equipment images object for an exercise
export const generateEquipmentImages = (equipment: string[]): { [equipment: string]: string } => {
  const images: { [equipment: string]: string } = {};
  equipment.forEach(eq => {
    images[eq] = getEquipmentImage(eq);
  });
  return images;
};
